export interface WarehouseProduct {
  warehouse_product_id: string;
  warehouse_id: string;
  product_id: string;
  quantity: number;
}

type NewWarehouseProduct = Omit<WarehouseProduct, "warehouse_product_id">;

const API_URL = "https://localhost:7278/api/warehouseproducts";

async function request<T>(
  path = "",
  options: RequestInit = {}
): Promise<T> {
  const response = await fetch(`${API_URL}${path}`, {
    ...options,
    headers: {
      "Content-Type": "application/json",
      ...options.headers,
    },
  });

  if (!response.ok) {
    const message = await response.text();
    throw new Error(message || `Request failed: ${response.status}`);
  }

  if (response.status === 204) {
    return undefined as T;
  }

  return response.json() as Promise<T>;
}

export const warehouseProductApi = {
  // READ: Get all warehouse products
  getAll: () => request<WarehouseProduct[]>(),

  // READ: Get warehouse product by ID
  getById: (id: string) =>
    request<WarehouseProduct>(`/${encodeURIComponent(id)}`),

  // CREATE: ID is generated by the C# controller
  create: (warehouseProduct: NewWarehouseProduct) =>
    request<WarehouseProduct>("", {
      method: "POST",
      body: JSON.stringify(warehouseProduct),
    }),

  // UPDATE
  update: (warehouseProduct: WarehouseProduct) =>
    request<void>(`/${encodeURIComponent(warehouseProduct.warehouse_product_id)}`, {
      method: "PUT",
      body: JSON.stringify(warehouseProduct),
    }),

  // DELETE
  delete: (id: string) =>
    request<void>(`/${encodeURIComponent(id)}`, {
      method: "DELETE",
    }),
};
